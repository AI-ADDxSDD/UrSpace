export function createMockKnowledgeMasteryResponse(
  nodes: ConceptMasteryNode[] = mockConceptMasteryNodes,
): ConceptMasteryResponseDto {
  const { distribution, averageMasteryScore } = calculateMasteryDistribution(nodes)
  const subjects = Array.from(new Set(nodes.map((n) => n.subject))).sort()
  const topics = Array.from(new Set(nodes.map((n) => n.topic))).sort()

  return {
    totalNodes: nodes.length,
    averageMasteryScore,
    distribution,
    nodes,
    subjects,
    topics,
    demoThresholds: DEMO_MASTERY_THRESHOLDS,
    disclaimer: KNOWLEDGE_MASTERY_DISCLAIMER,
  }
}
